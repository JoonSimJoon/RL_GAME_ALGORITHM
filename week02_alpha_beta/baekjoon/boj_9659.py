#!/usr/bin/env python3
"""
백준 9659: 돌 게임 5 (Silver III)

문제:
- N개의 돌이 있고, 상근이와 창영이가 번갈아가며 게임
- 한 번에 1개 또는 3개의 돌을 가져갈 수 있음
- 마지막 돌을 가져가는 사람이 승리
- 상근이가 선공, 둘 다 완벽하게 플레이할 때 승자는?

풀이:
- N이 매우 클 수 있음 (10^18 이하)
- DP로는 메모리 초과 → 패턴 찾기

패턴 분석:
N=1: 상근이 1개 가져감 → SK 승
N=2: 상근이 1개 → 창영이 1개 → CY 승
N=3: 상근이 3개 가져감 → SK 승
N=4: 상근이 1개 → 창영이 3개 → CY 승
N=5: 상근이 3개 → 창영이가 2개 남음 → 창영이 1개 → 상근이 1개 → SK 승

규칙:
- 홀수: SK 승
- 짝수: CY 승

증명:
- N이 홀수면 상근이가 1개를 가져가서 짝수로 만듦
  → 이후 창영이가 1개 가져가면 1개, 3개 가져가면 3개를 상근이가 가져감
  → 항상 상근이가 마지막
- N이 짝수면 창영이가 위 전략 사용
"""

import sys

def solve():
    N = int(sys.stdin.readline().strip())

    if N % 2 == 1:
        print("SK")
    else:
        print("CY")


if __name__ == "__main__":
    solve()
