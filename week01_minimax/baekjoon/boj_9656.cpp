// 백준 9656번: 돌 게임 2
// 난이도: Silver V
// 분류: 게임 이론 / DP / 수학
//
// 풀이 핵심:
// - N개의 돌, 한 턴에 1개 또는 3개 가져갈 수 있음
// - 마지막 돌을 가져가는 사람이 패배
// - 상근이가 먼저 시작
//
// 수학적 접근:
// - N이 짝수면 상근 승리
// - N이 홀수면 창영 승리
// - 9655번과 정반대 결과
//
// 이유:
// - N=1: 상근이 1개 가져가서 패배 → 창영 승리
// - N=2: 상근이 1개 가져감 → 창영이 1개 가져가서 패배 → 상근 승리
// - N=3: 상근이 1개 가져감 → 창영이 1개 가져감 → 상근이 1개 가져가서 패배 → 창영 승리
// - N=4: 상근 승리
// - 패턴: 짝수는 상근, 홀수는 창영

#include <bits/stdc++.h>
using namespace std;

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int N;
    cin >> N;

    if (N % 2 == 0) {
        cout << "SK" << '\n';  // 상근
    } else {
        cout << "CY" << '\n';  // 창영
    }

    return 0;
}
