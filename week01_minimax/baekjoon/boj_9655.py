# 백준 9655번: 돌 게임
# 난이도: Silver V
# 분류: 게임 이론 / DP / 수학
#
# 풀이 핵심:
# - N개의 돌, 한 턴에 1개 또는 3개 가져갈 수 있음
# - 마지막 돌을 가져가는 사람이 승리
# - 상근이가 먼저 시작
#
# 수학적 접근:
# - N이 홀수면 상근 승리
# - N이 짝수면 창영 승리
#
# 이유:
# - N=1: 상근이 1개 가져가서 승리
# - N=2: 상근이 1개 가져감 → 창영이 1개 가져가서 승리
# - N=3: 상근이 3개 가져가서 승리
# - N=4: 상근이 1개 또는 3개 가져가도 창영이 승리
# - 패턴: 홀수는 상근, 짝수는 창영

N = int(input())

if N % 2 == 1:
    print("SK")  # 상근
else:
    print("CY")  # 창영
